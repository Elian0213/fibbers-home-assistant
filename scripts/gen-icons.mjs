/**
 * gen-icons.mjs — inline the Solar icons we use into src/icons.gen.js.
 *
 * Reads the icon names from scripts/icon-map.json, pulls each icon's SVG body
 * from @iconify-json/solar (a devDependency), and writes a committed registry.
 * Run with: `bun run gen-icons`. No network at runtime — this is build-time only.
 *
 * A mapped name that doesn't exist in the package throws, so the map can't
 * silently drift from reality.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

const solar = JSON.parse(
  readFileSync(
    join(root, "node_modules/@iconify-json/solar/icons.json"),
    "utf8",
  ),
);
const map = JSON.parse(readFileSync(join(here, "icon-map.json"), "utf8"));

const defW = solar.width || 24;
const defH = solar.height || 24;

const names = [...new Set(Object.entries(map).filter(([k]) => k !== "_comment").map(([, v]) => v))].sort();

const out = {};
const missing = [];
for (const name of names) {
  const icon = solar.icons[name];
  if (!icon) {
    missing.push(name);
    continue;
  }
  const w = icon.width || defW;
  const h = icon.height || defH;
  out["solar:" + name] = { body: icon.body, vb: `0 0 ${w} ${h}` };
}

if (missing.length) {
  console.error("gen-icons: these Solar icons do not exist:\n  " + missing.join("\n  "));
  process.exit(1);
}

const header = `/* GENERATED by scripts/gen-icons.mjs from @iconify-json/solar — do not edit.
 * Re-generate with: bun run gen-icons  (after editing scripts/icon-map.json) */\n`;
const body = `export const ICONS = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(join(root, "src/icons.gen.js"), header + body);

console.log(`gen-icons: wrote ${Object.keys(out).length} icons to src/icons.gen.js`);
